export function BottomNav() {
  const { role } = useRole();

  const getNavItems = (): NavItem[] => {
    if (!role) return PATIENT_NAV; // default for uninitialized

    switch (role) {
      case 'patient':
        return PATIENT_NAV;
      case 'clinician':
        return CLINICIAN_NAV;
      case 'chw':
        return CHW_NAV;
      case 'admin':
        return ADMIN_NAV;
      default:
        return PATIENT_NAV;
    }
  };

  const navItems = getNavItems();

  return (
    <motion.nav 
      initial={{ y: 50, opacity: 0 }}
      animate={{ y: 0, opacity: 1 }}
      transition={{ type: "spring", bounce: 0.4, duration: 0.8 }}
      className="fixed bottom-0 inset-x-0 h-16 bg-slate-900/80 backdrop-blur-lg border-t border-slate-800/50 z-40"
    >
      <ul className="flex items-center justify-around h-full">
        {navItems.map(({ to, label, icon }) => (
          <li key={to} className="flex-1 h-full">
            <NavLink
              to={to}
              className={({ isActive }) =>
                `flex flex-col items-center justify-center h-full gap-1 transition-all duration-200 ${
                  isActive ? "text-teal-400" : "text-slate-500 hover:text-slate-300"
                }`
              }
            >
              {({ isActive }) => (
                <>
                  <motion.div 
                    className="h-6 w-6"
                    animate={isActive ? { y: [0, -4, 0] } : {}}
                    transition={{ duration: 0.3 }}
                  >
                    {icon}
                  </motion.div>
                  <span className="text-[10px] font-medium leading-none">{label}</span>
                </>
              )}
            </NavLink>
          </li>
        ))}
      </ul>
    </motion.nav>
  );
}
